// Draws the Mirepoix logos (D13): the M mark with lowercase "mirepoix"
// lettered in Fredoka. The letters become plain SVG shapes, so no font ever
// ships with the app. Fredoka (SIL Open Font License) is only read here, from
// a copy cached under node_modules/.cache.
// Run `npm run logos` after changing app/icons/icon.svg or the layout below.
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const ICONS = new URL('../app/icons/', import.meta.url);
const CACHE = new URL('../node_modules/.cache/mirepoix/', import.meta.url);
const FONT_CSS = 'https://fonts.googleapis.com/css2?family=Fredoka:wght@600';
const NAME = 'mirepoix';
const TILE = 512; // the mark's own size, in its units
const COLORS = { '': '#A84A18', '-dark': '#F0894A' }; // --carrot, light and dark

const font = parseFont(await fredoka());
const mark = markFrom(await readFile(new URL('icon.svg', ICONS), 'utf8'));
const word = lettering(font, NAME);

for (const [suffix, color] of Object.entries(COLORS)) {
  await writeFile(new URL(`logo-horizontal${suffix}.svg`, ICONS), horizontal(color));
  await writeFile(new URL(`logo-stacked${suffix}.svg`, ICONS), stacked(color));
  console.log(`logo-horizontal${suffix}.svg, logo-stacked${suffix}.svg`);
}

/** The mark on the left, the name beside it, its x-height centred on the mark. */
function horizontal(/** @type {string} */ color) {
  const size = (TILE * 0.42) / (font.xHeight / font.unitsPerEm);
  const text = word(size);
  const gap = TILE * 0.22;
  const baseline = TILE / 2 + (font.xHeight * size) / font.unitsPerEm / 2;
  const x = TILE + gap - text.left;
  return svg(TILE + gap + text.right - text.left, TILE, mark(0, 0), text.path(x, baseline, color));
}

/** The mark on top, the name centred underneath, a little wider than the mark. */
function stacked(/** @type {string} */ color) {
  const width = TILE * 1.3;
  const size = (width / (word(1000).right - word(1000).left)) * 1000;
  const text = word(size);
  const top = TILE + TILE * 0.14 - text.top;
  const height = top + text.bottom;
  return svg(width, height, mark((width - TILE) / 2, 0), text.path(-text.left, top, color));
}

/**
 * @param {number} width
 * @param {number} height
 * @param {...string} content
 */
function svg(width, height, ...content) {
  const w = round(width);
  const h = round(height);
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${round(w / 8)}" height="${round(h / 8)}">`,
    '  <!-- Generated by tools/make-logos.js (npm run logos). Edit there, not here. -->',
    '  <title>Mirepoix</title>',
    ...content.map((part) => `  ${part}`),
    '</svg>',
    '',
  ].join('\n');
}

/**
 * The mark from icon.svg, as a rounded tile that can be placed anywhere.
 * @param {string} source
 */
function markFrom(source) {
  const inner = source
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '');
  return (/** @type {number} */ x, /** @type {number} */ y) =>
    `<svg x="${round(x)}" y="${round(y)}" width="${TILE}" height="${TILE}" viewBox="0 0 ${TILE} ${TILE}">`
    + `<clipPath id="tile"><rect width="${TILE}" height="${TILE}" rx="${TILE * 0.22}"/></clipPath>`
    + `<g clip-path="url(#tile)">${inner}</g></svg>`;
}

/**
 * Lays out a word in a font, as an SVG path with its ink bounds.
 * @param {ReturnType<typeof parseFont>} font
 * @param {string} text
 */
function lettering(font, text) {
  return (/** @type {number} */ size) => {
    const scale = size / font.unitsPerEm;
    const bounds = { left: Infinity, right: -Infinity, top: Infinity, bottom: -Infinity };
    /** @type {{ x: number, y: number, on: boolean }[][]} */
    const contours = [];
    let pen = 0;
    for (const char of text) {
      const glyph = font.glyphIndex(char);
      for (const contour of font.contours(glyph)) {
        const placed = contour.map((point) => ({ x: (pen + point.x) * scale, y: -point.y * scale, on: point.on }));
        for (const { x, y } of placed) {
          bounds.left = Math.min(bounds.left, x);
          bounds.right = Math.max(bounds.right, x);
          bounds.top = Math.min(bounds.top, y);
          bounds.bottom = Math.max(bounds.bottom, y);
        }
        contours.push(placed);
      }
      pen += font.advance(glyph);
    }
    const d = contours.map(contourPath).join('');
    return {
      ...bounds,
      path: (/** @type {number} */ x, /** @type {number} */ y, /** @type {string} */ color) =>
        `<path fill="${color}" transform="translate(${round(x)} ${round(y)})" d="${d}"/>`,
    };
  };
}

/**
 * A TrueType contour (quadratic curves, on- and off-curve points) as SVG path data.
 * @param {{ x: number, y: number, on: boolean }[]} contour
 */
function contourPath(contour) {
  if (contour.length === 0) return '';
  const points = [...contour];
  const first = /** @type {{ x: number, y: number, on: boolean }} */ (points[0]);
  if (!first.on) {
    const last = /** @type {{ x: number, y: number, on: boolean }} */ (points.at(-1));
    points.unshift(last.on ? /** @type {typeof last} */ (points.pop()) : { x: (last.x + first.x) / 2, y: (last.y + first.y) / 2, on: true });
  }
  const at = (/** @type {{ x: number, y: number }} */ point) => `${round(point.x)} ${round(point.y)}`;
  const start = /** @type {{ x: number, y: number, on: boolean }} */ (points[0]);
  let d = `M${at(start)}`;
  /** @type {{ x: number, y: number } | null} */
  let control = null;
  for (const point of [...points.slice(1), start]) {
    if (point.on) {
      d += control ? `Q${at(control)} ${at(point)}` : `L${at(point)}`;
      control = null;
    } else {
      if (control) d += `Q${at(control)} ${at({ x: (control.x + point.x) / 2, y: (control.y + point.y) / 2 })}`;
      control = point;
    }
  }
  return `${d}Z`;
}

/** Fredoka 600 as a TrueType file, fetched once and cached. */
async function fredoka() {
  const file = new URL('fredoka-600.ttf', CACHE);
  try {
    return new Uint8Array(await readFile(file));
  } catch {
    // An old browser's user agent gets TrueType rather than WOFF2.
    const headers = { 'User-Agent': 'Mozilla/4.0' };
    const css = await (await fetch(FONT_CSS, { headers })).text();
    const url = /url\((https:[^)]+\.ttf)\)/.exec(css)?.[1];
    if (!url) throw new Error(`No TrueType font in ${FONT_CSS}`);
    const bytes = new Uint8Array(await (await fetch(url, { headers })).arrayBuffer());
    await mkdir(CACHE, { recursive: true });
    await writeFile(file, bytes);
    return bytes;
  }
}

/**
 * Just enough of a TrueType reader to get glyph outlines and advances.
 * @param {Uint8Array} bytes
 */
function parseFont(bytes) {
  const data = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  /** @type {Record<string, number>} */
  const tables = {};
  for (let i = 0, count = data.getUint16(4); i < count; i++) {
    const at = 12 + i * 16;
    tables[String.fromCharCode(...bytes.subarray(at, at + 4))] = data.getUint32(at + 8);
  }
  const table = (/** @type {string} */ tag) => {
    const offset = tables[tag];
    if (offset === undefined) throw new Error(`The font has no ${tag} table`);
    return offset;
  };
  const head = table('head');
  const glyf = table('glyf');
  const loca = table('loca');
  const hmtx = table('hmtx');
  const longLoca = data.getInt16(head + 50) === 1;
  const metrics = data.getUint16(table('hhea') + 34);
  const glyphStart = (/** @type {number} */ glyph) =>
    glyf + (longLoca ? data.getUint32(loca + glyph * 4) : data.getUint16(loca + glyph * 2) * 2);

  /**
   * @param {number} glyph
   * @returns {{ x: number, y: number, on: boolean }[][]}
   */
  const contours = (glyph) => {
    const start = glyphStart(glyph);
    if (start === glyphStart(glyph + 1)) return [];
    const count = data.getInt16(start);
    let p = start + 10;
    if (count < 0) return composite(p);
    const ends = [];
    for (let i = 0; i < count; i++, p += 2) ends.push(data.getUint16(p));
    const total = (ends.at(-1) ?? -1) + 1;
    p += 2 + data.getUint16(p); // skip the hinting instructions
    const flags = [];
    while (flags.length < total) {
      const flag = data.getUint8(p++);
      flags.push(flag);
      if (flag & 8) for (let repeat = data.getUint8(p++); repeat > 0; repeat--) flags.push(flag);
    }
    const coordinates = (/** @type {number} */ short, /** @type {number} */ same) => {
      let value = 0;
      return flags.map((flag) => {
        if (flag & short) value += flag & same ? data.getUint8(p++) : -data.getUint8(p++);
        else if (!(flag & same)) { value += data.getInt16(p); p += 2; }
        return value;
      });
    };
    const xs = coordinates(2, 16);
    const ys = coordinates(4, 32);
    const points = flags.map((flag, i) => ({ x: xs[i] ?? 0, y: ys[i] ?? 0, on: (flag & 1) === 1 }));
    return ends.map((end, i) => points.slice(i === 0 ? 0 : (ends[i - 1] ?? 0) + 1, end + 1));
  };

  /**
   * A glyph built from other glyphs, each moved and possibly scaled.
   * @param {number} p
   */
  const composite = (p) => {
    /** @type {{ x: number, y: number, on: boolean }[][]} */
    const result = [];
    const f2dot14 = (/** @type {number} */ at) => data.getInt16(at) / 16384;
    let flags;
    do {
      flags = data.getUint16(p);
      const part = data.getUint16(p + 2);
      p += 4;
      let dx;
      let dy;
      if (flags & 1) { dx = data.getInt16(p); dy = data.getInt16(p + 2); p += 4; } else { dx = data.getInt8(p); dy = data.getInt8(p + 1); p += 2; }
      let [a, b, c, d] = [1, 0, 0, 1];
      if (flags & 8) { a = d = f2dot14(p); p += 2; } else if (flags & 0x40) { a = f2dot14(p); d = f2dot14(p + 2); p += 4; } else if (flags & 0x80) { [a, b, c, d] = [f2dot14(p), f2dot14(p + 2), f2dot14(p + 4), f2dot14(p + 6)]; p += 8; }
      for (const contour of contours(part)) {
        result.push(contour.map(({ x, y, on }) => ({ x: a * x + c * y + dx, y: b * x + d * y + dy, on })));
      }
    } while (flags & 0x20);
    return result;
  };

  return {
    unitsPerEm: data.getUint16(head + 18),
    xHeight: data.getInt16(table('OS/2') + 86),
    advance: (/** @type {number} */ glyph) => data.getUint16(hmtx + Math.min(glyph, metrics - 1) * 4),
    glyphIndex: unicodeLookup(data, table('cmap')),
    contours,
  };
}

/**
 * Character → glyph, from the font's Unicode (format 4) character map.
 * @param {DataView} data
 * @param {number} cmap
 */
function unicodeLookup(data, cmap) {
  let sub = -1;
  for (let i = 0, count = data.getUint16(cmap + 2); i < count && sub < 0; i++) {
    const platform = data.getUint16(cmap + 4 + i * 8);
    const encoding = data.getUint16(cmap + 6 + i * 8);
    const offset = cmap + data.getUint32(cmap + 8 + i * 8);
    if ((platform === 0 || (platform === 3 && encoding === 1)) && data.getUint16(offset) === 4) sub = offset;
  }
  if (sub < 0) throw new Error('The font has no Unicode character map');
  const segments = data.getUint16(sub + 6) / 2;
  const ends = sub + 14;
  const starts = ends + segments * 2 + 2;
  const deltas = starts + segments * 2;
  const ranges = deltas + segments * 2;
  return (/** @type {string} */ char) => {
    const code = char.codePointAt(0) ?? 0;
    for (let i = 0; i < segments; i++) {
      if (code > data.getUint16(ends + i * 2)) continue;
      const start = data.getUint16(starts + i * 2);
      if (code < start) return 0;
      const delta = data.getInt16(deltas + i * 2);
      const range = data.getUint16(ranges + i * 2);
      if (range === 0) return (code + delta) & 0xffff;
      const glyph = data.getUint16(ranges + i * 2 + range + (code - start) * 2);
      return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
    }
    return 0;
  };
}

/** @param {number} value */
function round(value) {
  return Math.round(value * 10) / 10;
}
